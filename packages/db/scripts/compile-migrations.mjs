import {readdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';

const migrationsDir = path.resolve(process.cwd(), 'drizzle');
const outputPath = path.resolve(process.cwd(), 'src', 'migrations.compiled.ts');

const readMigrations = async () => {
    let entries = [];

    try {
        entries = await readdir(migrationsDir, {withFileTypes: true});
    } catch (error) {
        if (error?.code !== 'ENOENT') {
            throw error;
        }

        return [];
    }

    const sqlFiles = entries
        .filter(entry => entry.isFile() && entry.name.endsWith('.sql'))
        .map(entry => entry.name)
        .sort();

    const compiled = [];

    for (const filename of sqlFiles) {
        const filePath = path.join(migrationsDir, filename);
        const sql = await readFile(filePath, 'utf8');
        const id = filename.replace(/\.sql$/u, '');

        compiled.push({id, sql});
    }

    return compiled;
};

const compiledMigrations = await readMigrations();

const output = `// This file is auto-generated by scripts/compile-migrations.mjs. Do not edit by hand.\n\n`
    + `export const compiledMigrations = ${JSON.stringify(compiledMigrations, null, 4)} as const;\n`;

await writeFile(outputPath, output, 'utf8');

console.info(`Compiled ${compiledMigrations.length} migrations -> ${outputPath}`);
