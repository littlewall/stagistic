import {execFileSync} from 'node:child_process';
import {
    mkdir,
    readFile,
    writeFile,
} from 'node:fs/promises';

import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {compile} from 'json-schema-to-typescript';

const schemas = JSON.parse(execFileSync('cargo', [
    'run',
    '--locked',
    '-q',
    '-p',
    'stagistic-mcp-protocol',
    '--bin',
    'export_contract',
], {encoding: 'utf8'}));
const output = new URL('../src/generated/', import.meta.url);

/*
 * Validators are compiled here, at build time: compiling them in the app needs
 * `new Function`, which the Mac app's Content Security Policy forbids.
 */
const VALIDATED = {
    LocalRequest: 'checkRequest',
    UiRequest: 'checkUiRequest',
    UiReply: 'checkReply',
};
const ajv = new Ajv2020({
    strict: false,
    allErrors: false,
    code: {
        source: true,
        esm: true,
    },
    formats: {
        uint: true,
        uint32: true,
        uint64: true,
    },
});

for (const name of Object.keys(VALIDATED)) {
    ajv.addSchema(schemas[name], name);
}

// Ajv's ESM output still loads its runtime helpers with `require`; turn those into imports.
const runtimeImports = [];
const validatorCode = standaloneCode(ajv, Object.fromEntries(Object.entries(VALIDATED).map(([name, exportName]) => [exportName, name])))
    .replace(/require\("(ajv\/dist\/runtime\/[\w-]+)"\)\.default/g, (_, path) => {
        const binding = `runtime${runtimeImports.length}`;

        runtimeImports.push(
            `import ${binding}Module from '${path}.js';`,
            `const ${binding} = typeof ${binding}Module === 'function' ? ${binding}Module : ${binding}Module.default;`,
        );

        return binding;
    })
    .replace(/^"use strict";/, '');

if (validatorCode.includes('require(') || validatorCode.includes('new Function')) {
    throw new Error('Generated MCP validators still call require() or new Function.');
}

const validators = {
    'validators.js': [
        '// Generated by scripts/contract.mjs. Do not edit.',
        ...runtimeImports,
        validatorCode,
        '',
    ].join('\n'),
    'validators.d.ts': [
        '// Generated by scripts/contract.mjs. Do not edit.',
        ...Object.entries(VALIDATED).flatMap(([name, exportName]) => [
            `import type {${name}} from './${name}';`,
            `export declare const ${exportName}: (value: unknown) => value is ${name};`,
        ]),
        '',
    ].join('\n'),
};

await mkdir(output, {recursive: true});
for (const [name, schema] of Object.entries({...schemas, validators: null})) {
    const files = name === 'validators' ? validators : {[`${name}.json`]: `${JSON.stringify(schema, null, 2)}\n`};

    if (name !== 'tools' && name !== 'validators') {
        files[`${name}.ts`] = await compile(schema, name, {$refOptions: {resolve: {external: false}}});
    }

    for (const [file, content] of Object.entries(files)) {
        const target = new URL(file, output);

        if (process.argv.includes('--check')) {
            if (await readFile(target, 'utf8') !== content) {
                throw new Error(`Stale generated MCP contract: ${file}`);
            }
        } else {
            await writeFile(target, content);
        }
    }
}
