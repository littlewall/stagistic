import assert from 'node:assert/strict';
import {
    existsSync,
    mkdirSync,
    mkdtempSync,
    readFileSync,
    writeFileSync,
} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {describe, it} from 'node:test';

import {renderAgent} from '../lib/render.mjs';
import {syncAgents} from '../lib/sync.mjs';

const ROLES = [
    'scout',
    'implementer',
    'verifier',
    'reviewer',
    'researcher',
];

const repo = (roles = {}) => {
    const cwd = mkdtempSync(path.join(tmpdir(), 'agent-roles-sync-'));

    mkdirSync(path.join(cwd, '.agents'));
    writeFileSync(path.join(cwd, '.agents', 'roles.json'), JSON.stringify({roles}));

    return cwd;
};
const setRoles = (cwd, roles) => writeFileSync(path.join(cwd, '.agents', 'roles.json'), JSON.stringify({roles}));
const sync = (cwd, options) => syncAgents({
    cwd,
    home: mkdtempSync(path.join(tmpdir(), 'agent-roles-home-')),
    ...options,
});
const agentFile = (cwd, role) => readFileSync(path.join(cwd, '.claude', 'agents', `${role}.md`), 'utf8');

describe('renderAgent', () => {
    const body = 'Finds code.\n\nMore instructions.\n';

    it('renders claude role with configured model, effort and tools', () => {
        const text = renderAgent({
            role: 'scout',
            provider: 'claude',
            model: 'haiku',
            effort: 'low',
            tools: ['Read', 'Grep'],
            fallback: null,
        }, body, 'prompts/scout.md');

        assert.match(text, /^---\nname: scout\ndescription: "Finds code\."\nmodel: haiku\neffort: low\ntools: Read, Grep\n---\n/);
        assert.match(text, /generated by agent-roles sync from prompts\/scout\.md/);
        assert.doesNotMatch(text, /external:/);
        assert.ok(text.endsWith(body));
    });

    it('renders external role with fallback model and external marker', () => {
        const text = renderAgent({
            role: 'reviewer',
            provider: 'codex',
            model: 'gpt-6.1-sol',
            effort: 'ultra',
            tools: ['Read'],
            fallback: {model: 'opus', effort: 'max'},
        }, body, 'prompts/reviewer.md');

        assert.match(text, /\nmodel: opus\neffort: max\n/);
        assert.match(text, /<!-- external: codex\/gpt-6\.1-sol\/ultra -->/);
    });
});

describe('syncAgents', () => {
    it('ignores user-level config so committed agents stay reproducible', () => {
        const cwd = repo();
        const home = mkdtempSync(path.join(tmpdir(), 'agent-roles-home-'));

        mkdirSync(path.join(home, '.config', 'agent-roles'), {recursive: true});
        writeFileSync(
            path.join(home, '.config', 'agent-roles', 'roles.json'),
            JSON.stringify({roles: {reviewer: {
                provider: 'codex',
                model: 'gpt-6.1-sol',
                effort: 'high',
            }}}),
        );
        syncAgents({cwd, home});
        assert.doesNotMatch(agentFile(cwd, 'reviewer'), /external:/);
    });

    it('writes one agent file per role', () => {
        const cwd = repo();
        const result = sync(cwd);

        assert.deepEqual(result.errors, []);
        assert.equal(result.written.length, ROLES.length);

        for (const role of ROLES) {
            assert.match(agentFile(cwd, role), new RegExp(`^---\\nname: ${role}\\n`));
        }
    });

    it('switching external back to claude removes marker', () => {
        const cwd = repo({reviewer: {
            provider: 'codex',
            model: 'gpt-6.1-sol',
            effort: 'high',
        }});

        sync(cwd);
        assert.match(agentFile(cwd, 'reviewer'), /external: codex/);

        setRoles(cwd, {reviewer: {
            provider: 'claude',
            model: 'sonnet',
            effort: 'medium',
        }});
        sync(cwd);
        assert.doesNotMatch(agentFile(cwd, 'reviewer'), /external:/);
        assert.match(agentFile(cwd, 'reviewer'), /\nmodel: sonnet\neffort: medium\n/);
    });

    it('check reports drift for hand-edited file and writes nothing', () => {
        const cwd = repo();

        sync(cwd);

        const file = path.join(cwd, '.claude', 'agents', 'scout.md');

        writeFileSync(file, 'hand edit');

        const result = sync(cwd, {check: true});

        assert.deepEqual(result.drift, [file]);
        assert.deepEqual(result.written, []);
        assert.equal(readFileSync(file, 'utf8'), 'hand edit');
    });

    it('check reports missing files as drift', () => {
        const cwd = repo();

        assert.equal(sync(cwd, {check: true}).drift.length, ROLES.length);
        assert.equal(existsSync(path.join(cwd, '.claude')), false);
    });

    it('validation errors abort without writing any file', () => {
        const cwd = repo({implementer: {provider: 'codex', model: 'gpt-6.1-sol'}});
        const result = sync(cwd);

        assert.ok(result.errors.includes('implementer: write roles must use provider claude or opencode'));
        assert.deepEqual(result.written, []);
        assert.equal(existsSync(path.join(cwd, '.claude')), false);
    });

    it('sync is idempotent', () => {
        const cwd = repo();

        sync(cwd);

        const second = sync(cwd);

        assert.deepEqual(second.written, []);
        assert.deepEqual(sync(cwd, {check: true}).drift, []);
    });

    it('sync removes nothing it did not generate', () => {
        const cwd = repo();
        const other = path.join(cwd, '.claude', 'agents', 'other.md');

        mkdirSync(path.dirname(other), {recursive: true});
        writeFileSync(other, 'mine');
        sync(cwd);
        assert.equal(readFileSync(other, 'utf8'), 'mine');
    });
});
