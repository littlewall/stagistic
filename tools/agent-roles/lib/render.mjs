/** Claude Code agent file for a resolved role; external roles run on their Claude fallback. */
export const renderAgent = (resolved, promptBody, promptPath) => {
    const {model, effort} = resolved.fallback ?? resolved;
    const description = promptBody.split('\n').find(line => line.trim() !== '').trim();
    const lines = [
        '---',
        `name: ${resolved.role}`,
        `description: ${JSON.stringify(description)}`,
        `model: ${model}`,
        `effort: ${effort}`,
        `tools: ${resolved.tools.join(', ')}`,
        '---',
        `<!-- generated by agent-roles sync from ${promptPath}; edit roles.json or the prompt, then run sync -->`,
    ];

    if (resolved.fallback) {
        // OpenCode picks its model at run time from the role's candidates, so the marker names the tier.
        const target = resolved.provider === 'opencode' ? `tier-${resolved.tier}` : resolved.model;

        lines.push(`<!-- external: ${resolved.provider}/${target}/${resolved.effort} -->`);
    }

    return `${lines.join('\n')}\n${promptBody}`;
};

/** OpenCode agents are separate from Synara threads; permissions follow the role's fixed kind. */
export const renderOpenCodeAgent = (resolved, promptBody) => {
    const bash = resolved.kind === 'read' ? 'deny' : resolved.kind === 'execute' ? {
        '*': 'deny',
        'moon run root:verify *': 'allow',
        'git status*': 'allow',
        'git diff*': 'allow',
    } : {
        '*': 'allow',
        'git *': 'deny',
        'git status*': 'allow',
        'git diff*': 'allow',
        'git log*': 'allow',
        'git show*': 'allow',
        'git ls-files*': 'allow',
        'gh *': 'deny',
        'glab *': 'deny',
    };
    const permission = {
        '*': 'deny',
        read: 'allow',
        glob: 'allow',
        grep: 'allow',
        edit: resolved.kind === 'write' ? 'allow' : 'deny',
        bash,
        task: 'deny',
        skill: 'deny',
        question: 'deny',
    };
    const permissions = JSON.stringify(permission, null, 4).split('\n').map((line, index) => index === 0 ? `permission: ${line}` : `  ${line}`);

    return [
        '---',
        `description: ${JSON.stringify(promptBody.split('\n')[0])}`,
        'mode: primary',
        ...permissions,
        '---',
        '<!-- generated by agent-roles sync; edit roles.json or prompts, then run sync -->',
        'You are a bounded worker, not the session orchestrator. Do not start a feature/fix flow or delegate. Return decisions and blockers to the caller.',
        'Run commands in the foreground; do not start background jobs, daemons, or detached services. The caller owns cancellation and handoff.',
        promptBody,
    ].join('\n');
};
